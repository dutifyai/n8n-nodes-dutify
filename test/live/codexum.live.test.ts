import { afterAll, beforeAll, expect, it } from 'vitest';
import {
	cleanupStack,
	liveDescribe,
	loadOptionsOf,
	run,
	runError,
	runOne,
	runId,
	wikiKey,
} from './harness';

liveDescribe('Codexum space and page — live', () => {
	const cleanup = cleanupStack();
	const key = wikiKey('NL');
	let page = '';
	let child = '';

	beforeAll(async () => {
		const created = await runOne('codexumSpace', 'create', {
			key,
			name: `n8n-live wiki ${runId}`,
			additionalFields: { description: 'live test' },
		});
		expect(created).toMatchObject({ key, name: `n8n-live wiki ${runId}` });
		cleanup.add(`wiki space ${key}`, async () => await runOne('codexumSpace', 'delete', { space: key }));
	});
	afterAll(async () => await cleanup.run());

	it('space: list, picker, get, getWithPages, update', async () => {
		const spaces = await run('codexumSpace', 'list', { returnAll: true });
		expect(spaces.map((s) => s.key)).toContain(key);
		expect((await loadOptionsOf('getWikiSpaces')).map((o) => o.value)).toContain(key);
		expect((await run('workspace', 'listWikiSpaces')).map((s) => s.key)).toContain(key);
		expect(await runOne('codexumSpace', 'get', { space: key })).toMatchObject({ key });
		expect(await runOne('codexumSpace', 'getWithPages', { space: key })).toEqual(expect.any(Object));
		const updated = await runOne('codexumSpace', 'update', {
			space: key,
			updateFields: { name: `n8n-live wiki renamed ${runId}` },
		});
		expect(updated).toMatchObject({ name: `n8n-live wiki renamed ${runId}` });
	});

	it('space public settings: get, check a slug, set a hero title (kept disabled)', async () => {
		const settings = await runOne('codexumSpace', 'getPublicSettings', { space: key });
		expect(settings).toEqual(expect.any(Object));
		const slug = await runOne('codexumSpace', 'checkPublicSlug', {
			space: key,
			slug: `n8n-live-${runId}`,
		});
		expect(slug).toEqual(expect.any(Object));
		const set = await runOne('codexumSpace', 'setPublicSettings', {
			space: key,
			settings: { heroTitle: `Hero ${runId}`, isEnabled: false },
		});
		expect(set).toMatchObject({ heroTitle: `Hero ${runId}` });
		const again = await runOne('codexumSpace', 'getPublicSettings', { space: key });
		expect(again).toMatchObject({ heroTitle: `Hero ${runId}`, isEnabled: false });
	});

	it('page: create with Markdown (title with & and /), get returns the Markdown, pickers list it', async () => {
		const created = await runOne('codexumPage', 'create', {
			space: key,
			title: `Q&A / notes ${runId}`,
			markdown: `# Heading\n\nSome **bold** text ${runId}.\n\n- one\n- two\n`,
		});
		page = String(created.slug);
		expect(page).toMatch(/\S/);

		const fetched = await runOne('codexumPage', 'get', { space: key, page });
		expect(fetched.title).toBe(`Q&A / notes ${runId}`);
		expect(String(fetched.markdown)).toContain('**bold**');
		expect(String(fetched.markdown)).toContain('- one');

		expect((await loadOptionsOf('getWikiPages', { space: key })).map((o) => o.value)).toContain(page);
		const parents = await loadOptionsOf('getWikiParentPages', { space: key });
		expect(parents[0]).toEqual({ name: '- Top Level -', value: '' });
	});

	// Slugs are generated by the server and never contain '/'. The node encodes the slug with
	// encodeURIComponent, so a slash travels as %2F: the request must still reach the page route
	// and answer a plain 404 (not a routing 400/405).
	it('a slug containing / is sent as %2F and answers 404', async () => {
		const error = await runError('codexumPage', 'get', { space: key, page: `no/such/${runId}` });
		expect(error.httpCode).toBe('404');
		expect(error.message).toMatch(/page/i);
	});

	it('page: a blank page gets an empty Markdown string', async () => {
		const blank = await runOne('codexumPage', 'create', { space: key, title: `Blank ${runId}` });
		const fetched = await runOne('codexumPage', 'get', { space: key, page: String(blank.slug) });
		expect(fetched.markdown).toBe('');
		await runOne('codexumPage', 'delete', { space: key, page: String(blank.slug) });
	});

	it('page: update replaces title and body; child page; list by parent; move to top level', async () => {
		const updated = await runOne('codexumPage', 'update', {
			space: key,
			page,
			updateFields: { title: `Notes ${runId}`, markdown: `Replaced body ${runId}` },
		});
		expect(updated).toMatchObject({ title: `Notes ${runId}` });
		const fetched = await runOne('codexumPage', 'get', { space: key, page });
		expect(String(fetched.markdown)).toContain(`Replaced body ${runId}`);

		const created = await runOne('codexumPage', 'create', {
			space: key,
			title: `Child ${runId}`,
			parent: page,
		});
		child = String(created.slug);
		const children = await run('codexumPage', 'list', { space: key, parent: page, returnAll: true });
		expect(children.map((c) => c.slug)).toContain(child);

		await runOne('codexumPage', 'move', { space: key, page: child });
		const roots = await run('codexumPage', 'list', { space: key, returnAll: true });
		expect(roots.map((c) => c.slug)).toEqual(expect.arrayContaining([page, child]));
	});

	// Public page sharing is a Business plan feature; the test workspace is on FREE.
	it('page share link: getShare answers; enableShare is refused on FREE with the plan named', async () => {
		expect(await runOne('codexumPage', 'getShare', { space: key, page })).toEqual(expect.any(Object));
		const error = await runError('codexumPage', 'enableShare', {
			space: key,
			page,
			options: { showAuthor: false },
		});
		expect(error.message).toContain('Business');
	});

	// FREE cannot share a page, so disableShare is checked on a page that is not shared: the
	// catalog's 204 (sharing off; nothing to revoke), and 404 for a page that does not exist.
	it('page disableShare: an unshared page answers success and stays unshared; unknown page 404', async () => {
		expect(await runOne('codexumPage', 'disableShare', { space: key, page })).toEqual({
			success: true,
		});
		expect(await runOne('codexumPage', 'getShare', { space: key, page })).toMatchObject({
			isEnabled: false,
		});
		const unknown = await runError('codexumPage', 'disableShare', {
			space: key,
			page: `no-such-page-${runId}`,
		});
		expect(unknown.httpCode).toBe('404');
	});

	it('search and retrieve answer (the index may lag, so only the shape is checked)', async () => {
		const found = await run('codexumPage', 'search', {
			query: `Replaced body ${runId}`,
			options: { spaceKey: key, limit: 5 },
		});
		expect(Array.isArray(found)).toBe(true);
		const retrieved = await run('codexumPage', 'retrieve', {
			query: 'notes',
			options: { spaceKey: key, limit: 3 },
		});
		expect(Array.isArray(retrieved)).toBe(true);
	});

	it('page delete archives it; permanent delete removes it (404)', async () => {
		expect(await runOne('codexumPage', 'delete', { space: key, page: child })).toEqual({
			success: true,
		});
		expect(await runOne('codexumPage', 'get', { space: key, page: child })).toMatchObject({
			status: 'archived',
		});
		expect(
			await runOne('codexumPage', 'delete', { space: key, page: child, permanent: true }),
		).toEqual({ success: true });
		const gone = await runError('codexumPage', 'get', { space: key, page: child });
		expect(gone.httpCode).toBe('404');
	});
});
